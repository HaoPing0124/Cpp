/*
题意：
    给定一个由单词和空格组成的字符串 s，
    返回字符串中最后一个单词的长度。

    单词只由字母组成，
    字符串中可能存在多个连续空格，
    最后一个单词后面也可能存在空格。

思路：
    从字符串末尾向前遍历。

    先跳过字符串末尾的所有空格，
    此时 i 指向最后一个单词的最后一个字符。

    然后继续向前遍历，
    只要当前位置不是空格，
    就将单词长度加 1。

    遇到空格或者遍历到字符串开头时结束，
    得到的长度就是最后一个单词的长度。

时间复杂度：O(n)
空间复杂度：O(1)
*/

#include "Algorithm_150.h"

class Solution
{
public:
    int lengthOfLastWord(string s)
    {
        int i = static_cast<int>(s.size()) - 1;

        // 跳过字符串末尾的空格
        while (i >= 0 && s[i] == ' ')
        {
            --i;
        }

        int res = 0;

        // 统计最后一个单词的长度
        while (i >= 0 && s[i] != ' ')
        {
            ++res;
            --i;
        }

        return res;
    }
};