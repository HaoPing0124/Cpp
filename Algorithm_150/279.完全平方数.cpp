/*
题意：
    给定一个整数 n，
    返回和为 n 的完全平方数的最少数量。
    完全平方数是某个整数的平方，例如：1、4、9、16、25 ...
    每个完全平方数可以重复使用。

思路：
    使用动态规划。
    定义：
        f[i] 表示组成整数 i 所需要的最少完全平方数数量。

    对于当前整数 i，
    枚举所有不超过 i 的完全平方数 j * j。

    如果最后选择一个 j * j，
    那么前面的部分需要组成：
        i - j * j

    因此状态转移为：
        f[i] = min(f[i], f[i - j * j] + 1)

    初始化：
        f[0] = 0

    其余位置初始化为一个较大的值，
    然后从 1 到 n 依次计算。

时间复杂度：O(n × sqrt(n))
空间复杂度：O(n)
*/

#include "Algorithm_150.h"

class Solution
{
public:
    int numSquares(int n)
    {
        // f[i] 表示组成 i 需要的最少完全平方数数量
        vector<int> f(n + 1, n + 1);
        f[0] = 0;

        for (int i = 1; i <= n; ++i)
        {
            // 枚举所有不超过 i 的完全平方数
            for (int j = 1; j * j <= i; ++j)
            {
                f[i] = min(f[i], f[i - j * j] + 1);
            }
        }

        return f[n];
    }
};